export function translateDynamicArabic(text: string): string {
  const raw = String(text ?? '');
  if (!raw) return raw;
  const trimmed = raw.trim();
  if (AR_TO_EN_MAP[trimmed]) return AR_TO_EN_MAP[trimmed];

  // Dynamic patterns
  let m: RegExpMatchArray | null;

  m = trimmed.match(/^تعارض يحتاج مراجعة \((\d+)\)$/);
  if (m) return `Conflicts need review (${m[1]})`;

  m = trimmed.match(/^عمل محلي دون إنترنت \((\d+) معلقة\)$/);
  if (m) return `Offline mode (${m[1]} pending)`;

  m = trimmed.match(/^مزامنة معلقة \((\d+)\)$/);
  if (m) return `Pending sync (${m[1]})`;

  m = trimmed.match(/^خطأ في الاستجابة \((\d+)\)$/);
  if (m) return `Response error (${m[1]})`;

  m = trimmed.match(/^تعذر إتمام ربط الجهاز \((\d+)\)$/);
  if (m) return `Could not complete device pairing (${m[1]})`;

  m = trimmed.match(/^تم ربط التطبيق بسيرفر \((.*)\) عبر رابط دعوة$/);
  if (m) return `App paired with server (${m[1]}) via invite link`;

  m = trimmed.match(/^تم ربط الجهاز بسيرفر \((.*)\)\. بانتظار اعتماد مدير النظام، ثم أدخل بيانات حسابك للدخول\.$/);
  if (m) return `Device paired with server (${m[1]}). Waiting for admin approval, then enter your credentials to log in.`;

  m = trimmed.match(/^تم إعداد الاتصال تلقائياً بسيرفر \((.*)\)\. يرجى تسجيل الدخول باسم المستخدم وكلمة المرور المعتادة\.$/);
  if (m) return `Connection configured automatically with server (${m[1]}). Please log in with your username and password.`;

  m = trimmed.match(/^تم اكتشاف السيرفر المركزي تلقائياً \((.*)\)$/);
  if (m) return `Central server auto-discovered (${m[1]})`;

  m = trimmed.match(/^تم اكتشاف السيرفر المركزي تلقائياً على الشبكة المحلية \((.*)\)\. يرجى تسجيل الدخول بحسابك\.$/);
  if (m) return `Central server auto-discovered on LAN (${m[1]}). Please sign in with your account.`;

  return raw;
}
