import { isNativeCapacitor, saveAndShareDocument } from '../../services/native';
import { getActiveDir, getActiveLanguage, getActiveLocale, tr } from '../../i18n/translator';
import type {
  CustomPrintDocType,
  CustomPrintField,
  RepPhonePrintConfig,
} from '../../types';

// Bilingual RTL/LTR Print-to-PDF Engine using a hidden iframe on Desktop/Web
// and native Filesystem + Share on Android/iOS Capacitor apps.

export interface ActivePrintTemplateConfig {
  showLogo?: boolean;
  footerText?: string;
  repPhoneConfig?: RepPhonePrintConfig;
  customPrintFields?: CustomPrintField[];
}

let activePrintTemplateConfig: ActivePrintTemplateConfig = {};

export function setActivePrintTemplateConfig(cfg?: ActivePrintTemplateConfig | null): void {
  activePrintTemplateConfig = cfg ? { ...cfg } : {};
}

export function getActivePrintTemplateConfig(): ActivePrintTemplateConfig {
  return activePrintTemplateConfig;
}

export function resolvePrintDocCategory(rawDocType?: string): CustomPrintDocType {
  const txt = String(rawDocType || '').toLowerCase();
  if (!txt) return 'all';
  if (txt.includes('مرتجع') || txt.includes('return')) return 'return';
  if (txt.includes('عرض سعر') || txt.includes('quote')) return 'quote';
  if (txt.includes('شراء') || txt.includes('مشتريات') || txt.includes('purchase')) return 'purchase';
  if (txt.includes('كشف') || txt.includes('statement') || txt.includes('حساب') || txt.includes('ledger')) return 'statement';
  if (txt.includes('عهد') || txt.includes('تحويل') || txt.includes('custody') || txt.includes('transfer')) return 'custody';
  if (txt.includes('بيع') || txt.includes('مبيعات') || txt.includes('فاتورة') || txt.includes('sale') || txt.includes('invoice')) return 'sales';
  return 'all';
}

export function formatCustomPrintFieldValue(field: CustomPrintField, locale: string): string {
  const raw = String(field.value ?? '').trim();
  if (!raw) return '';
  if (field.type === 'date') {
    const parsed = new Date(raw);
    if (!Number.isNaN(parsed.getTime())) {
      return parsed.toLocaleDateString(locale);
    }
  }
  if (field.type === 'number') {
    const num = Number(raw);
    if (Number.isFinite(num)) {
      return num.toLocaleString(locale);
    }
  }
  return raw;
}

export function getApplicableCustomPrintFields(
  fields: CustomPrintField[] | undefined,
  rawDocType?: string
): CustomPrintField[] {
  if (!Array.isArray(fields) || fields.length === 0) return [];
  const docCategory = resolvePrintDocCategory(rawDocType);
  return [...fields]
    .filter((f) => f && f.visible !== false && String(f.label || '').trim() && String(f.value ?? '').trim())
    .filter((f) => {
      const types = Array.isArray(f.docTypes) && f.docTypes.length > 0 ? f.docTypes : ['all'];
      return types.includes('all') || (docCategory !== 'all' && types.includes(docCategory));
    })
    .sort((a, b) => Number(a.order || 0) - Number(b.order || 0));
}

export interface PdfExportOptions {
  title: string;
  docTypeCategory?: string;
  subtitle?: string;
  companyName?: string;
  companySubtitle?: string;
  address?: string;
  phone1?: string;
  phone2?: string;
  branchName?: string;
  branchNumber?: string;
  representativeName?: string;
  representativePhone?: string;
  repPhoneConfig?: RepPhonePrintConfig;
  customPrintFields?: CustomPrintField[];
  commercialRegistration?: string;
  taxNumber?: string;
  docNumber?: string;
  dateRangeText?: string;
  meta?: Array<{ label: string; value: string }>;
  tableHeaders?: string[];
  tableRows?: Array<Array<string | number>>;
  summaryPairs?: Array<{ label: string; value: string; highlight?: boolean }>;
  notes?: string;
  footerText?: string;
}

function escapeHtml(raw: unknown): string {
  return String(raw ?? '')
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;');
}

export function buildPrintableHtml(options: PdfExportOptions): string {
  const lang = getActiveLanguage();
  const dir = getActiveDir();
  const locale = getActiveLocale();
  const isEn = lang === 'en';
  const textAlign = isEn ? 'left' : 'right';

  const tpl = activePrintTemplateConfig;

  const {
    title,
    docTypeCategory,
    subtitle,
    companyName = tr('مؤسسة أولاد سليم لتجارة المواد الغذائية بالجملة', 'AWLAD SELIM Wholesale Food Trading'),
    companySubtitle = 'AWLAD SELIM ERP',
    address,
    phone1,
    phone2,
    branchName,
    branchNumber,
    representativeName,
    representativePhone,
    repPhoneConfig = tpl.repPhoneConfig,
    customPrintFields = tpl.customPrintFields,
    commercialRegistration,
    taxNumber,
    docNumber,
    dateRangeText,
    meta = [],
    tableHeaders = [],
    tableRows = [],
    summaryPairs = [],
    notes,
    footerText = tpl.footerText ||
      tr(
        'تم إصدار هذا المستند آلياً من نظام أولاد سليم للمحاسبة وإدارة الأعمال',
        'Automatically generated by AWLAD SELIM Accounting & ERP System'
      ),
  } = options;

  const origin =
    typeof window !== 'undefined' && !window.location.origin.startsWith('capacitor://')
      ? window.location.origin
      : '';
  const generatedAt = new Date().toLocaleString(locale);

  const phoneLine = [phone1?.trim(), phone2?.trim()].filter(Boolean).join(' / ');
  const branchParts = [
    branchName?.trim() || '',
    branchNumber?.trim() ? `${tr('رقم الفرع', 'Branch No.')}: ${branchNumber.trim()}` : '',
  ].filter(Boolean);
  const branchLine = branchParts.join(' · ');

  const contactBits = [
    address?.trim() || '',
    phoneLine ? `${tr('هاتف', 'Phone')}: ${phoneLine}` : '',
  ].filter(Boolean);

  const showRepPhone = repPhoneConfig?.showInPrint !== false;
  const repPhoneLabel = (repPhoneConfig?.label || tr('هاتف المندوب', 'Rep Phone')).trim();
  const repPhonePlacement = repPhoneConfig?.placement || 'party_box';
  const resolvedRepPhone = (
    representativePhone?.trim() ||
    repPhoneConfig?.defaultPhone?.trim() ||
    ''
  ).trim();

  const applicableCustomFields = getApplicableCustomPrintFields(
    customPrintFields,
    docTypeCategory || title
  );
  const headerCustomFields = applicableCustomFields.filter((f) => f.placement === 'header');
  const companyInfoCustomFields = applicableCustomFields.filter((f) => f.placement === 'company_info');
  const partyInfoCustomFields = applicableCustomFields.filter((f) => f.placement === 'party_info');
  const footerCustomFields = applicableCustomFields.filter((f) => f.placement === 'footer');

  const enrichedMeta = meta.filter((m) => {
    if (!showRepPhone && (m.label.includes('هاتف المندوب') || /rep phone/i.test(m.label))) {
      return false;
    }
    return true;
  });
  if (
    representativeName?.trim() &&
    !enrichedMeta.some((m) => m.label.includes('المندوب') && !m.label.includes('هاتف'))
  ) {
    enrichedMeta.push({ label: tr('المندوب المسؤول', 'Representative'), value: representativeName.trim() });
  }
  if (
    showRepPhone &&
    repPhonePlacement === 'party_box' &&
    resolvedRepPhone &&
    !enrichedMeta.some((m) => m.label === repPhoneLabel || m.label.includes('هاتف المندوب') || /rep phone/i.test(m.label))
  ) {
    enrichedMeta.push({ label: repPhoneLabel, value: resolvedRepPhone });
  }
  if (branchLine && !enrichedMeta.some((m) => m.label.includes('الفرع') || /branch/i.test(m.label))) {
    enrichedMeta.push({ label: tr('الفرع', 'Branch'), value: branchLine });
  }
  for (const cf of partyInfoCustomFields) {
    const val = formatCustomPrintFieldValue(cf, locale);
    if (val) enrichedMeta.push({ label: cf.label, value: val });
  }

  const metaHtml = enrichedMeta.length
    ? `<div class="meta-grid">${enrichedMeta
        .filter((m) => String(m.value ?? '').trim() !== '')
        .map(
          (m) =>
            `<div class="meta-item"><span class="meta-label">${escapeHtml(m.label)}:</span> <strong>${escapeHtml(m.value)}</strong></div>`
        )
        .join('')}</div>`
    : '';

  const tableHtml =
    tableHeaders.length > 0
      ? `<table>
          <thead>
            <tr>${tableHeaders.map((h) => `<th>${escapeHtml(h)}</th>`).join('')}</tr>
          </thead>
          <tbody>
            ${
              tableRows.length > 0
                ? tableRows
                    .map(
                      (row) =>
                        `<tr>${row.map((cell) => `<td>${escapeHtml(cell)}</td>`).join('')}</tr>`
                    )
                    .join('')
                : `<tr><td colspan="${tableHeaders.length}" style="text-align:center;color:#64748b;">${escapeHtml(tr('لا توجد بيانات للعرض'))}</td></tr>`
            }
          </tbody>
        </table>`
      : '';

  const summaryHtml = summaryPairs.length
    ? `<div class="summary-box">${summaryPairs
        .map(
          (s) =>
            `<div class="summary-row ${s.highlight ? 'highlight' : ''}"><span>${escapeHtml(s.label)}</span><strong>${escapeHtml(s.value)}</strong></div>`
        )
        .join('')}</div>`
    : '';

  const legalParts = [commercialRegistration?.trim(), taxNumber?.trim()].filter(Boolean);
  const showLogo = tpl.showLogo !== false;

  const headerRepPhoneHtml =
    showRepPhone && repPhonePlacement === 'header' && resolvedRepPhone
      ? `<p><strong>${escapeHtml(repPhoneLabel)}:</strong> ${escapeHtml(resolvedRepPhone)}</p>`
      : '';

  const headerFieldsHtml =
    headerCustomFields.length > 0 || companyInfoCustomFields.length > 0
      ? `<div class="custom-header-fields">${[...companyInfoCustomFields, ...headerCustomFields]
          .map((cf) => `<span><strong>${escapeHtml(cf.label)}:</strong> ${escapeHtml(formatCustomPrintFieldValue(cf, locale))}</span>`)
          .join('')}</div>`
      : '';

  const footerExtraBits: string[] = [];
  if (showRepPhone && repPhonePlacement === 'footer' && resolvedRepPhone) {
    footerExtraBits.push(`${repPhoneLabel}: ${resolvedRepPhone}`);
  }
  for (const cf of footerCustomFields) {
    const v = formatCustomPrintFieldValue(cf, locale);
    if (v) footerExtraBits.push(`${cf.label}: ${v}`);
  }

  return `<!DOCTYPE html>
<html lang="${lang}" dir="${dir}">
<head>
  <meta charset="UTF-8" />
  <meta name="viewport" content="width=device-width, initial-scale=1.0" />
  <title>${escapeHtml(title)}</title>
  <style>
    @page { size: A4; margin: 14mm; }
    * { box-sizing: border-box; font-family: 'Cairo', 'Segoe UI', Tahoma, Arial, sans-serif; }
    body { margin: 0; padding: 12px; color: #0f172a; font-size: 12px; line-height: 1.5; direction: ${dir}; background: #fff; }
    .header { display: flex; justify-content: space-between; align-items: center; border-bottom: 2px solid #003589; padding-bottom: 12px; margin-bottom: 14px; }
    .header img { max-height: 58px; width: auto; }
    .company-info { text-align: center; flex: 1; padding: 0 12px; }
    .company-info h1 { margin: 0; font-size: 18px; color: #011E58; font-weight: 800; }
    .company-info p { margin: 2px 0 0; font-size: 11px; color: #475569; }
    .custom-header-fields { margin-top: 4px; display: flex; flex-wrap: wrap; justify-content: center; gap: 10px; font-size: 10.5px; color: #011E58; }
    .doc-badge { background: #EEF3FA; border: 1px solid #DCE6F5; border-radius: 8px; padding: 8px 12px; text-align: center; min-width: 120px; }
    .doc-badge .title { font-weight: 800; color: #011E58; font-size: 12px; display: block; }
    .doc-badge .num { font-family: monospace; font-weight: 800; color: #003589; font-size: 13px; }
    .meta-grid { display: grid; grid-template-columns: repeat(2, 1fr); gap: 8px; background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; padding: 10px 12px; margin-bottom: 14px; }
    .meta-label { color: #64748b; }
    table { width: 100%; border-collapse: collapse; margin-bottom: 14px; font-size: 11px; }
    th { background: #011E58; color: #fff; padding: 7px 8px; text-align: ${textAlign}; border: 1px solid #003589; font-weight: 700; }
    td { padding: 6px 8px; border: 1px solid #cbd5e1; text-align: ${textAlign}; }
    tr:nth-child(even) td { background: #f8fafc; }
    .summary-box { ${isEn ? 'margin-left: auto;' : 'margin-right: auto;'} width: 280px; border: 1px solid #cbd5e1; border-radius: 8px; padding: 10px 12px; background: #f8fafc; }
    .summary-row { display: flex; justify-content: space-between; padding: 4px 0; border-bottom: 1px dashed #e2e8f0; }
    .summary-row:last-child { border-bottom: 0; }
    .summary-row.highlight { font-size: 13px; color: #011E58; font-weight: 800; padding-top: 6px; }
    .notes { margin-top: 12px; padding: 8px 12px; background: #f8fafc; border: 1px solid #e2e8f0; border-radius: 8px; font-size: 11px; }
    .footer-extra { margin-top: 10px; display: flex; flex-wrap: wrap; gap: 12px; font-size: 10.5px; color: #011E58; font-weight: 600; }
    .footer { margin-top: 18px; padding-top: 8px; border-top: 1px solid #cbd5e1; display: flex; justify-content: space-between; font-size: 10px; color: #64748b; }
  </style>
</head>
<body>
  <div class="header">
    ${showLogo && origin ? `<img src="${origin}/awlad-selim-logo.png" alt="AWLAD SELIM" onerror="this.style.display='none'" />` : ''}
    <div class="company-info">
      <h1>${escapeHtml(companyName)}</h1>
      ${subtitle || companySubtitle ? `<p>${escapeHtml(subtitle || companySubtitle)}</p>` : ''}
      ${branchLine ? `<p><strong>${escapeHtml(branchLine)}</strong></p>` : ''}
      ${contactBits.length > 0 ? `<p>${escapeHtml(contactBits.join(' • '))}</p>` : ''}
      ${headerRepPhoneHtml}
      ${headerFieldsHtml}
      ${dateRangeText ? `<p>${escapeHtml(dateRangeText)}</p>` : ''}
    </div>
    <div class="doc-badge">
      <span class="title">${escapeHtml(title)}</span>
      ${docNumber ? `<span class="num">${escapeHtml(docNumber)}</span>` : ''}
    </div>
  </div>
  ${metaHtml}
  ${tableHtml}
  ${summaryHtml}
  ${notes || legalParts.length > 0 ? `<div class="notes">${notes ? `<div><strong>${escapeHtml(tr('ملاحظات:'))}</strong> ${escapeHtml(notes)}</div>` : ''}${legalParts.length > 0 ? `<div style="margin-top:4px;color:#64748b;">${escapeHtml(legalParts.join(' • '))}</div>` : ''}</div>` : ''}
  ${footerExtraBits.length > 0 ? `<div class="footer-extra">${footerExtraBits.map((b) => `<span>${escapeHtml(b)}</span>`).join('')}</div>` : ''}
  <div class="footer">
    <span>${escapeHtml(footerText)}</span>
    <span>${escapeHtml(tr('تاريخ الطباعة', 'Printed At'))}: ${escapeHtml(generatedAt)}</span>
  </div>
</body>
</html>`;
}

export function exportHtmlToPdf(options: PdfExportOptions): void {
  if (typeof document === 'undefined') return;
  const html = buildPrintableHtml(options);

  if (isNativeCapacitor()) {
    const fileLabel = options.docNumber || options.title || 'document';
    saveAndShareDocument({
      filename: `AWLAD_SELIM_${fileLabel}_${Date.now()}.html`,
      content: html,
      mimeType: 'text/html;charset=utf-8',
      title: `${options.title}${options.docNumber ? ` - ${options.docNumber}` : ''}`,
    }).catch(() => {});
    return;
  }

  const existing = document.getElementById('awlad-selim-pdf-iframe');
  if (existing) existing.remove();

  const iframe = document.createElement('iframe');
  iframe.id = 'awlad-selim-pdf-iframe';
  iframe.style.position = 'fixed';
  iframe.style.right = '0';
  iframe.style.bottom = '0';
  iframe.style.width = '0';
  iframe.style.height = '0';
  iframe.style.border = '0';
  iframe.style.opacity = '0';
  document.body.appendChild(iframe);

  const doc = iframe.contentWindow?.document;
  if (!doc) return;
  doc.open();
  doc.write(html);
  doc.close();

  const trigger = () => {
    try {
      iframe.contentWindow?.focus();
      iframe.contentWindow?.print();
    } finally {
      window.setTimeout(() => {
        iframe.remove();
      }, 2000);
    }
  };

  if (iframe.contentWindow) {
    iframe.onload = trigger;
    window.setTimeout(trigger, 300);
  }
}

export function exportTableToPdf(
  title: string,
  headers: string[],
  rows: Array<Array<string | number>>,
  extra?: Partial<PdfExportOptions>
): void {
  exportHtmlToPdf({
    title,
    tableHeaders: headers,
    tableRows: rows,
    ...extra,
  });
}
